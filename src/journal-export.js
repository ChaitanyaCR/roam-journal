import { downloadZip } from "client-zip";
import { renderStory } from "./story-renderer.js";

const extensions = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" };

function page(title) {
  const doc = document.implementation.createHTMLDocument(title);
  doc.head.insertAdjacentHTML("afterbegin", '<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">');
  const style = doc.createElement("style");
  style.textContent = "body{font:1.1rem/1.6 Georgia,serif;max-width:48rem;margin:2rem auto;padding:0 1rem;color:#252822}img{max-width:100%;height:auto}figure{margin:1rem 0}p,figcaption{white-space:pre-wrap}a{color:#295647}";
  doc.head.append(style);
  return doc;
}

function append(parent, tag, text) {
  const el = parent.ownerDocument.createElement(tag);
  el.textContent = text;
  parent.append(el);
  return el;
}

function html(doc) {
  return "<!doctype html>\n" + doc.documentElement.outerHTML;
}

function storyDocument(trip) {
  if (trip.document) return trip.document;
  const blocks = trip.blocks ?? [
    { type: "text", text: trip.story },
    ...trip.photos.map((_, index) => ({ type: "photo", index })),
  ];
  return { version: 1, type: "doc", content: blocks.map(block => block.type === "photo"
    ? { type: "image", attrs: { index: block.index, caption: trip.photos[block.index].alt || "" } }
    : { type: "paragraph", content: block.text ? [{ type: "text", text: block.text }] : [] }) };
}

export async function* journalFiles(trips, progress) {
  const index = page("Roam Journal");
  append(index.body, "h1", "Roam Journal");
  const list = append(index.body, "ul", "");
  if (!trips.length) append(index.body, "p", "Your journal has no active trips.");
  const records = [];
  for (const [i, trip] of trips.entries()) {
    const { id, title, destination, date, end_date, tags, city_pin } = trip;
    // IDs are generated by the Worker. Keep archive paths within their folder.
    if (!/^[a-z0-9_-]+$/i.test(id)) throw new Error("Invalid trip ID for “" + title + "”.");
    const folder = "trips/" + id + "/";
    const path = folder + "index.html";
    const dates = end_date && end_date !== date ? date + " – " + end_date : date;
    progress("Exporting " + (i + 1) + " of " + trips.length + " · " + title);
    const photos = [];
    for (const [j, photo] of trip.photos.entries()) {
      let blob;
      try {
        const response = await fetch("/api/photos/" + encodeURIComponent(photo.key), { cache: "no-store" });
        if (!response.ok) throw new Error();
        blob = await response.blob();
        if (!extensions[blob.type] || !blob.size) throw new Error();
      } catch {
        throw new Error("Could not read photo " + (j + 1) + " in “" + title + "”.");
      }
      const name = folder + "photo-" + (j + 1) + "." + extensions[blob.type];
      photos.push({ path: name, alt: photo.alt });
      yield { name, input: blob };
    }
    const content = storyDocument(trip);
    const doc = page(title);
    append(doc.body, "a", "All trips").setAttribute("href", "../../index.html");
    append(doc.body, "h1", title);
    append(doc.body, "p", [destination, dates].filter(Boolean).join(" · "));
    if (tags?.length) append(doc.body, "p", tags.join(" · "));
    if (city_pin) append(doc.body, "p", [city_pin.label, city_pin.provider, city_pin.attribution, city_pin.sourceUrl, city_pin.license].filter(Boolean).join(" · "));
    doc.body.append(renderStory(content, trip.photos, (_, j) => photos[j].path.slice(folder.length), doc));
    yield { name: path, input: html(doc) };
    append(append(list, "li", ""), "a", title + " · " + dates).setAttribute("href", path);
    records.push({ id, title, destination, date, end_date, tags, city_pin, path, document: content, photos });
  }
  yield { name: "index.html", input: html(index) };
  yield { name: "journal.json", input: JSON.stringify({ version: 1, trips: records }, null, 2) };
}

export async function exportJournal(progress) {
  const filename = "roam-journal.zip";
  let handle;
  if (window.showSaveFilePicker) {
    try {
      handle = await window.showSaveFilePicker({ suggestedName: filename });
    } catch (error) {
      // Embedded journals can have a picker but lack permission to open it.
      if (error.name !== "SecurityError") throw error;
    }
  }
  const response = await fetch("/api/trips", { cache: "no-store" });
  if (!response.ok) throw new Error("Could not load your saved trips.");
  const archive = downloadZip(journalFiles(await response.json(), progress));
  if (handle) {
    await archive.body.pipeTo(await handle.createWritable());
    return "Journal ZIP saved.";
  }
  const url = URL.createObjectURL(await archive.blob());
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 60000);
  return "Journal ZIP ready. Download started.";
}
